#!/usr/bin/env python3
"""Generate docs/catalogue.md and the catalogue section of README.md from docs/catalogue.csv.

    python tools/build_catalogue.py

docs/catalogue.csv is the source of truth (one row per script):
    category,file,title,description,requires,impact
"""
from __future__ import annotations

import csv
import re
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "docs" / "catalogue.csv"
MD = ROOT / "docs" / "catalogue.md"
README = ROOT / "README.md"

CATEGORIES = OrderedDict([
    ("active-directory", ("Active Directory", "users, computers, groups, OUs, GPOs, LAPS, DC event logs, DHCP")),
    ("entra-id", ("Entra ID & Microsoft Graph", "devices, guests, Conditional Access, MFA, sign-ins, licences")),
    ("exchange-online", ("Exchange Online", "mailboxes, forwarding, delegates, distribution lists, message purge")),
    ("sharepoint-teams", ("SharePoint & Teams", "sites, owners, access audits")),
    ("defender-kql", ("Microsoft Defender — KQL hunting", "advanced-hunting queries and MDE health checks")),
    ("endpoint", ("Endpoint administration", "local admins, registry, software, Windows Update, printers, agents, USB")),
    ("network", ("Network", "Nmap, open ports, connection monitoring, Meraki, geolocation")),
    ("compliance-audits", ("Recurring compliance checks", "scheduled jobs that audit AD/Entra and e-mail a report")),
    ("utilities", ("Utilities", "CSV, files, Excel-driven updates, backups")),
])


def rows() -> list[dict[str, str]]:
    with CSV.open(encoding="utf-8", newline="") as f:
        data = list(csv.DictReader(f))
    for r in data:
        path = ROOT / "scripts" / r["category"] / r["file"]
        if not path.exists():
            raise SystemExit(f"catalogue.csv references a missing file: scripts/{r['category']}/{r['file']}")
    on_disk = {p.relative_to(ROOT / "scripts").as_posix() for p in (ROOT / "scripts").rglob("*") if p.is_file()}
    listed = {f"{r['category']}/{r['file']}" for r in data}
    missing = sorted(on_disk - listed)
    if missing:
        raise SystemExit("scripts on disk but not in catalogue.csv: " + ", ".join(missing))
    return sorted(data, key=lambda r: (list(CATEGORIES).index(r["category"]), r["file"].lower()))


def impact_badge(impact: str) -> str:
    low = impact.lower()
    if low.startswith("read"):
        return "🟢 read-only"
    return "🟠 " + impact


def main() -> None:
    data = rows()
    by_cat: dict[str, list[dict[str, str]]] = OrderedDict((c, []) for c in CATEGORIES)
    for r in data:
        by_cat[r["category"]].append(r)

    out = ["# Script catalogue", "", f"{len(data)} scripts. Generated by `tools/build_catalogue.py` from `docs/catalogue.csv` — edit the CSV, not this file.", ""]
    summary = ["| Category | Scripts | Scope |", "|----------|--------:|-------|"]
    for cat, (label, scope) in CATEGORIES.items():
        n = len(by_cat[cat])
        if n:
            summary.append(f"| [{label}](docs/catalogue.md#{re.sub(r'[^a-z0-9]+', '-', label.lower()).strip('-')}) | {n} | {scope} |")
    for cat, (label, scope) in CATEGORIES.items():
        items = by_cat[cat]
        if not items:
            continue
        out += [f"## {label}", "", f"*{scope}*", "", "| Script | What it does | Requires | Impact |", "|--------|--------------|----------|--------|"]
        for r in items:
            out.append(f"| [`{r['file']}`](../scripts/{cat}/{r['file']}) | {r['description']} | {r['requires']} | {impact_badge(r['impact'])} |")
        out.append("")
    MD.write_text("\n".join(out), encoding="utf-8", newline="\n")

    readme = README.read_text(encoding="utf-8")
    block = "\n".join(summary)
    new = re.sub(r"(<!-- catalogue:start -->\n).*?(<!-- catalogue:end -->)", lambda m: m.group(1) + block + "\n" + m.group(2), readme, flags=re.S)
    new = re.sub(r"\*\*(N|\d+) scripts\*\*", f"**{len(data)} scripts**", new)
    README.write_text(new, encoding="utf-8", newline="\n")
    print(f"catalogue: {len(data)} scripts in {sum(1 for c in by_cat.values() if c)} categories")


if __name__ == "__main__":
    main()
